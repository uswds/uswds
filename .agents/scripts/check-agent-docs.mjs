#!/usr/bin/env node
/**
 * Verify that the repo's agent documentation still describes the repo.
 *
 * Agent docs go stale silently: a script gets renamed, a directory moves, and
 * `AGENTS.md` keeps confidently telling every agent to run a command that no
 * longer exists. This checks the claims that are mechanically checkable:
 *
 *   1. Every `npm run <script>` an agent doc mentions exists in package.json.
 *   2. Every `gulp <task>` an agent doc mentions is exported from gulpfile.js.
 *   3. Every repo path an agent doc mentions exists on disk.
 *   4. The Node version AGENTS.md states matches `.nvmrc`.
 *   5. Every skill in `.agents/skills/` has a `.claude/skills/` pointer so
 *      Claude Code can discover it, with matching frontmatter names.
 *
 * Run with `npm run agents:check`.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");

/** Docs that make claims about the repo, and are therefore checked. */
export const DOC_FILES = ["AGENTS.md", ".agents/README.md"];

/**
 * Paths that are generated by a build rather than committed, so a doc may
 * legitimately mention them before they exist in a fresh clone.
 */
const GENERATED_PREFIXES = [
  "dist",
  "_site",
  "node_modules",
  "storybook-static",
  "html-templates",
  "src/stylesheets/lib",
];

/** Remove fenced code blocks, which hold illustrative examples, not claims. */
export function stripFencedBlocks(markdown) {
  return markdown.replace(/^```[\s\S]*?^```/gm, "");
}

/** Collect the contents of every single-backtick inline code span. */
export function inlineCodeSpans(markdown) {
  return [...stripFencedBlocks(markdown).matchAll(/`([^`\n]+)`/g)].map(
    (match) => match[1],
  );
}

/** npm scripts a doc tells an agent to run. */
export function referencedNpmScripts(spans) {
  const scripts = new Set();
  spans.forEach((span) => {
    const runMatch = span.match(/^npm run ([\w:-]+)/);
    if (runMatch) scripts.add(runMatch[1]);
    const bareMatch = span.match(/^npm (test|start)$/);
    if (bareMatch) scripts.add(bareMatch[1]);
  });
  return [...scripts];
}

/** Gulp tasks a doc tells an agent to run. */
export function referencedGulpTasks(spans) {
  const tasks = new Set();
  spans.forEach((span) => {
    const match = span.match(/^(?:npx )?gulp ([\w:-]+)/);
    if (match) tasks.add(match[1]);
  });
  return [...tasks];
}

/**
 * Repo paths a doc mentions.
 *
 * An inline code span holds prose, shell, and identifiers as well as paths, so
 * a span only counts as a path when its first segment is a real top-level entry
 * in the repo. That admits `packages/usa-button/src/index.js`, `gulpfile.js`,
 * and `.nvmrc` while rejecting `const`, `sinon`, and `window.uswdsPresent`.
 * Spans holding a placeholder or glob are skipped as illustrative.
 */
export function referencedPaths(spans, topLevelEntries) {
  const paths = new Set();
  spans.forEach((span) => {
    if (/[<>*?|\s(){}]/.test(span)) return;
    if (/^(https?:|\/|~)/.test(span)) return;
    const cleaned = span.replace(/^\.\//, "").replace(/[.,;:]+$/, "");
    if (!cleaned) return;
    const [firstSegment] = cleaned.split("/");
    if (!topLevelEntries.has(firstSegment)) return;
    paths.add(cleaned.replace(/\/$/, ""));
  });
  return [...paths];
}

function isGenerated(path) {
  return GENERATED_PREFIXES.some(
    (prefix) => path === prefix || path.startsWith(`${prefix}/`),
  );
}

/**
 * Resolve a documented path.
 *
 * `src/` is both a top-level directory and the source directory of all 88
 * packages, so a span like `src/usa-accordion.twig` is package-relative even
 * though its first segment matches a root entry. Those resolve against any
 * package as well as against the root.
 */
export function pathExists(root, path, packageNames) {
  if (existsSync(join(root, path))) return true;
  if (!path.startsWith("src/")) return false;
  return packageNames.some((pkg) =>
    existsSync(join(root, "packages", pkg, path)),
  );
}

/** Read the `name:` field out of a SKILL.md frontmatter block. */
export function frontmatterName(markdown) {
  const match = markdown.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return null;
  const nameLine = match[1].match(/^name:\s*(.+)$/m);
  return nameLine ? nameLine[1].trim() : null;
}

function checkSkillDiscoverability(root) {
  const problems = [];
  const agentSkillsDir = join(root, ".agents", "skills");
  if (!existsSync(agentSkillsDir)) return problems;

  readdirSync(agentSkillsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .forEach((entry) => {
      const source = join(agentSkillsDir, entry.name, "SKILL.md");
      if (!existsSync(source)) {
        problems.push(`.agents/skills/${entry.name}/ has no SKILL.md`);
        return;
      }
      const sourceName = frontmatterName(readFileSync(source, "utf8"));
      if (sourceName !== entry.name) {
        problems.push(
          `.agents/skills/${entry.name}/SKILL.md frontmatter name is "${sourceName}", expected "${entry.name}"`,
        );
      }

      const pointer = join(root, ".claude", "skills", entry.name, "SKILL.md");
      if (!existsSync(pointer)) {
        problems.push(
          `skill "${entry.name}" is not discoverable: add .claude/skills/${entry.name}/SKILL.md pointing at .agents/skills/${entry.name}/SKILL.md`,
        );
        return;
      }
      const pointerBody = readFileSync(pointer, "utf8");
      if (frontmatterName(pointerBody) !== entry.name) {
        problems.push(
          `.claude/skills/${entry.name}/SKILL.md frontmatter name does not match "${entry.name}"`,
        );
      }
      if (!pointerBody.includes(`.agents/skills/${entry.name}/SKILL.md`)) {
        problems.push(
          `.claude/skills/${entry.name}/SKILL.md does not point at .agents/skills/${entry.name}/SKILL.md`,
        );
      }
    });

  return problems;
}

function checkNodeVersion(root, agentsMd) {
  const nvmrcPath = join(root, ".nvmrc");
  if (!existsSync(nvmrcPath)) return [];
  const expected = readFileSync(nvmrcPath, "utf8").trim().split(".")[0];
  const nodeLine = agentsMd
    .split("\n")
    .find((line) => /^-\s*\*\*Node\*\*/.test(line));
  if (!nodeLine) {
    return ["AGENTS.md has no `**Node**:` bullet stating the runtime version"];
  }
  const stated = nodeLine.match(/\bv(\d+)/);
  if (!stated) {
    return [
      `AGENTS.md Node bullet does not state a version: ${nodeLine.trim()}`,
    ];
  }
  return stated[1] === expected
    ? []
    : [`AGENTS.md says Node v${stated[1]} but .nvmrc says ${expected}`];
}

/** Run every check. Returns a list of human-readable problems. */
export function checkAgentDocs(root = REPO_ROOT) {
  const problems = [];
  const packageJson = JSON.parse(
    readFileSync(join(root, "package.json"), "utf8"),
  );
  const definedScripts = new Set(Object.keys(packageJson.scripts ?? {}));
  const gulpfile = readFileSync(join(root, "gulpfile.js"), "utf8");
  const definedTasks = new Set(
    [...gulpfile.matchAll(/^exports\.([\w$]+)\s*=/gm)].map((match) => match[1]),
  );
  const topLevelEntries = new Set(readdirSync(root));
  const packageNames = existsSync(join(root, "packages"))
    ? readdirSync(join(root, "packages"), { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => entry.name)
    : [];

  DOC_FILES.forEach((docFile) => {
    const docPath = join(root, docFile);
    if (!existsSync(docPath)) {
      problems.push(`${docFile} is missing`);
      return;
    }
    const spans = inlineCodeSpans(readFileSync(docPath, "utf8"));

    referencedNpmScripts(spans)
      .filter((script) => !definedScripts.has(script))
      .forEach((script) =>
        problems.push(
          `${docFile} references \`npm run ${script}\`, which is not in package.json scripts`,
        ),
      );

    referencedGulpTasks(spans)
      .filter((task) => !definedTasks.has(task))
      .forEach((task) =>
        problems.push(
          `${docFile} references \`gulp ${task}\`, which gulpfile.js does not export`,
        ),
      );

    referencedPaths(spans, topLevelEntries)
      .filter((path) => !isGenerated(path))
      .filter((path) => !pathExists(root, path, packageNames))
      .forEach((path) =>
        problems.push(
          `${docFile} references \`${path}\`, which does not exist`,
        ),
      );
  });

  problems.push(
    ...checkNodeVersion(root, readFileSync(join(root, "AGENTS.md"), "utf8")),
  );
  problems.push(...checkSkillDiscoverability(root));

  return problems;
}

const isMain =
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const problems = checkAgentDocs();
  if (problems.length) {
    console.error(
      `Agent docs are out of date (${problems.length} problem${problems.length === 1 ? "" : "s"}):\n`,
    );
    problems.forEach((problem) => console.error(`  - ${problem}`));
    console.error("\nUpdate the doc, or the code it describes, and re-run.");
    process.exit(1);
  }
  console.log(`Agent docs check passed (${DOC_FILES.join(", ")}).`);
}
